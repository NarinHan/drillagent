import subprocess
import json
import os
import re
from pathlib import Path
from typing import Dict, List, Optional, Any

# llvm-cov: Either use this cli tool directly, or dump JSON data and parse it ourselves.
class LLVMCovUtils:
    """
    Utility class for parsing coverage data files (profraw/profdata) generated by instrumented binaries.
    Features:
    1. Generate coverage summary report.
    2. Query function coverage details (execution status, covered/uncovered lines, etc.).
    3. Query function region coverage.
    4. Query line coverage (execution status, count, owning function).
    5. Generate HTML coverage report.
    6. Clear cached data to free memory (coverage data can be 50+ MB).
    7. Get cache information and statistics.
    """
    def __init__(self, binary_abs_path: str, llvm_cov_path: str = "llvm-cov", llvm_profdata_path: str = "llvm-profdata"):
        """
        Initialize LLVMCovUtils.
        Args:
            binary_abs_path: Absolute path to instrumented binary
            llvm_cov_path: Path to llvm-cov tool (default: "llvm-cov")
            llvm_profdata_path: Path to llvm-profdata tool (default: "llvm-profdata")
        Note:
            Call update_profile_data(profraw_path) to set coverage data after initialization.
        """
        self.binary_path = os.path.abspath(binary_abs_path)
        self.llvm_cov_path = llvm_cov_path           # llvm-cov command
        self.llvm_profdata_path = llvm_profdata_path # llvm-profdata command

        # We don't maintain profraw path.
        self.profdata_path = "" # Path to the cov profdata file, should be updated after each new execution using update_profile_data().
        self.is_profile_empty = False # Whether the profraw file is empty.

        # Cache for exported JSON data (can be large, use clear_data() to free memory).
        self._coverage_data: Optional[Dict[str, Any]] = None

    def update_profile_data(self, profraw_path: str) -> None:
        # First clear self.profdata_path and self._coverage_data. Then re-generate these two fields from profraw_path.
        # Validate profraw_path format
        if not profraw_path.endswith('.profraw'):
            raise ValueError("Suffix of profraw_path must be .profraw")

        # Clear cached coverage data before updating
        self.clear_data()

        # Check if profraw file is empty
        if os.path.getsize(profraw_path) == 0:
            self.is_profile_empty = True
            print(f"LLVMCovUtil Warning: Provided profraw file is empty: {profraw_path}")
            return  # Skip conversion for empty profraw file

        self.is_profile_empty = False
        # Convert profraw to profdata and update path
        profraw_path = os.path.abspath(profraw_path)
        profdata_path = profraw_path.replace('.profraw', '.profdata')
        cmd = [
            self.llvm_profdata_path,
            'merge',
            profraw_path,
            '-o',
            profdata_path
        ]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            raise RuntimeError(f"Failed to convert profraw to profdata: {result.stderr}")
        self.profdata_path = profdata_path
        # The cov json data will be parsed lazily when needed.

    # Currently using self._coverage_data as cache.
    def _get_coverage_data(self) -> Dict[str, Any]:
        """
        Get full coverage data in JSON format (cached).
        Returns:
            Coverage data dictionary
        Raises:
            RuntimeError: If profile data is not set or is empty
        """
        if not self.profdata_path:
            raise RuntimeError("Profile data not set. Call update_profile_data() first")
        if self.is_profile_empty:
            raise RuntimeError("Profile data is empty. Cannot query coverage from empty profile.")
        if self._coverage_data is None:
            cmd = [
                self.llvm_cov_path,
                'export',
                self.binary_path,
                f'-instr-profile={self.profdata_path}',
                '-format=text'
            ]
            result = subprocess.run(cmd, capture_output=True, text=True)
            if result.returncode != 0:
                raise RuntimeError(f"llvm-cov command failed: {result.stderr}")
            self._coverage_data = json.loads(result.stdout)

        return self._coverage_data

    def get_function_coverage(self, file_path: str, function_name: str) -> Dict[str, Any]: # Based on JSON data
        """
        Get function coverage details.
        Args:
            file_path: Source file path
            function_name: Function name
        Returns:
            Dictionary containing:
            - is_executed: Whether function was executed
            - execution_count: Execution count
            - regions_covered: Number of covered regions
            - regions_total: Total number of regions
            - filenames: List of filenames associated with the function
        """
        coverage_data = self._get_coverage_data()
        file_path = os.path.abspath(file_path)

        # Why here we use traversal to find function? Because the functions are stored as list, not in a dict.
        # Functions are stored in data[0]['functions']
        for function in coverage_data.get('data', [{}])[0].get('functions', []):
            if function['name'] == function_name:
                # Check if this function belongs to the specified file
                filenames = function.get('filenames', [])
                abs_filenames = [os.path.abspath(f) for f in filenames]
                if file_path not in abs_filenames:
                    continue

                # Get the file_id for the target file
                file_id = abs_filenames.index(file_path)

                # Calculate region coverage
                # Region format: [start_line, start_col, end_line, end_col, execution_count, file_id, expanded_file_id, kind]
                regions = function.get('regions', [])
                regions_in_file = [r for r in regions if r[5] == file_id]
                regions_covered = sum(1 for r in regions_in_file if r[4] > 0)

                return {
                    'is_executed': function['count'] > 0,
                    'execution_count': function['count'],
                    'regions_covered': regions_covered,
                    'regions_total': len(regions_in_file),
                    'filenames': filenames # useless for us
                }
        # Anyone who calls this function should handle the exception with try-except.
        raise ValueError(f"Function '{function_name}' not found in file '{file_path}'")

    def get_multi_functions_coverage(self, function_with_filepath_list: List[tuple]) -> Dict[tuple, Dict[str, Any]]: # Based on JSON data
        """
        Get coverage details for multiple functions in batch.
        This is more efficient than calling get_function_coverage() multiple times.
        Args:
            function_with_filepath_list: List of (file_path, function_name) tuples
        Returns:
            Dictionary mapping (file_path, function_name) to coverage info dict containing:
            - is_executed: Whether function was executed
            - execution_count: Execution count
            - regions_covered: Number of covered regions
            - regions_total: Total number of regions
            - filenames: List of filenames associated with the function
            - found: Whether the function was found in coverage data
        Example:
            >>> functions = [('/path/to/main.c', 'main'), ('/path/to/foo.c', 'foo')]
            >>> results = cov_utils.get_multi_functions_coverage(functions)
            >>> print(results[('/path/to/main.c', 'main')]['is_executed'])
        """
        # Get coverage data once for all functions
        coverage_data = self._get_coverage_data()

        # Convert input list to set for faster lookup and normalize file paths
        target_functions = {}
        for file_path, func_name in function_with_filepath_list:
            abs_file_path = os.path.abspath(file_path)
            target_functions[(abs_file_path, func_name)] = {
                'found': False,
                'is_executed': False,
                'execution_count': 0,
                'regions_covered': 0,
                'regions_total': 0,
                'filenames': []
            }

        # Traverse all functions in coverage data
        for function in coverage_data.get('data', [{}])[0].get('functions', []):
            function_name = function['name']
            filenames = function.get('filenames', [])
            abs_filenames = [os.path.abspath(f) for f in filenames]

            # Check if this function matches any target
            for abs_file_path in abs_filenames:
                key = (abs_file_path, function_name)
                if key in target_functions:
                    # Found a match - get the file_id for the target file
                    file_id = abs_filenames.index(abs_file_path)

                    # Calculate region coverage
                    # Region format: [start_line, start_col, end_line, end_col, execution_count, file_id, expanded_file_id, kind]
                    regions = function.get('regions', [])
                    regions_in_file = [r for r in regions if r[5] == file_id]
                    regions_covered = sum(1 for r in regions_in_file if r[4] > 0)

                    # Update result
                    target_functions[key] = {
                        'found': True,
                        'is_executed': function['count'] > 0,
                        'execution_count': function['count'],
                        'regions_covered': regions_covered,
                        'regions_total': len(regions_in_file),
                        'filenames': filenames
                    }

        return target_functions

    def get_detailed_function_coverage(self, file_path: str, function_name: str) -> str: # Based on llvm-cov show command
        """
        Get detailed line-by-line coverage for a specific function in a human-readable format.
        Uses llvm-cov show command to get the coverage output directly.

        Args:
            file_path: Source file path (will be converted to absolute path)
            function_name: Function name to show coverage for

        Returns:
            Formatted string showing line-by-line coverage with execution counts and source code.
            Output from llvm-cov show command.

        Example:
            >>> cov_utils = LLVMCovUtils(binary_path='/path/to/binary')
            >>> cov_utils.update_profile_data('/path/to/coverage.profraw')
            >>> result = cov_utils.get_detailed_function_coverage('/path/to/source.c', 'main')
            >>> print(result)
        """
        file_path = os.path.abspath(file_path)

        # Construct llvm-cov show command
        # Format: llvm-cov show <binary> <source_file> -instr-profile=<profdata> --name=<function_name>
        cmd = [
            self.llvm_cov_path,
            'show',
            self.binary_path,
            file_path,
            f'-instr-profile={self.profdata_path}',
            f'--name={function_name}'
        ]

        # Execute the command
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            raise RuntimeError(f"llvm-cov show command failed: {result.stderr}")

        # Return the output directly
        return result.stdout


    def get_line_coverage(self, file_path: str, line_number: int) -> Dict[str, Any]: # Based on llvm-cov show command
        """
        Get line coverage details using llvm-cov show command.

        This method uses llvm-cov show to get accurate line-level coverage information
        by parsing the formatted output directly, avoiding the complexity of manually
        handling segment ranges from JSON data.

        Args:
            file_path: Source file path
            line_number: Line number (1-indexed)
        Returns:
            Dictionary containing:
            - is_executed: Whether line was executed
            - execution_count: Execution count
        """
        file_path = os.path.abspath(file_path)

        # Construct llvm-cov show command to get line counts for the entire file
        # Format: llvm-cov show <binary> -instr-profile=<profdata> --show-line-counts <file>
        cmd = [
            self.llvm_cov_path,
            'show',
            self.binary_path,
            f'-instr-profile={self.profdata_path}',
            '--show-line-counts',
            file_path
        ]

        # Execute the command
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            raise RuntimeError(f"llvm-cov show command failed: {result.stderr}")

        # Parse the output to find the target line
        # Expected formats:
        #   "  42|      5|   if (x > 0) {"       - regular count
        #   "  42|  2.14M|   if (x > 0) {"       - millions
        #   "  42|   410k|   if (x > 0) {"       - thousands
        #
        # Pattern explanation:
        #   ^\s*           - optional leading whitespace
        #   (\d+)          - line number (group 1)
        #   \|             - separator
        #   \s*            - optional whitespace
        #   ([0-9.]+[kKMGT]?)  - execution count with optional suffix (group 2)
        #   \|             - separator
        pattern = re.compile(r'^\s*(\d+)\|\s*([0-9.]+[kKMGT]?)\|')

        for line in result.stdout.split('\n'):
            match = pattern.match(line)
            if match:
                current_line_num = int(match.group(1))
                count_str = match.group(2)

                # Parse execution count for count_str
                # Count string (e.g., "42", "2.14M", "410k"). We want standard integer.
                count_str = count_str.strip()
                # Suffix multipliers
                multipliers = {
                    'k': 1000, 'K': 1000,
                    'm': 1000000, 'M': 1000000,
                    'g': 1000000000, 'G': 1000000000,
                    't': 1000000000000, 'T': 1000000000000
                }
                # Check if the last character is a suffix
                if count_str and count_str[-1] in multipliers:
                    # Extract numeric part and multiply
                    numeric_part = float(count_str[:-1])
                    count_int = int(numeric_part * multipliers[count_str[-1]])
                else:
                    # No suffix, just convert to int
                    count_int = int(float(count_str))

                # Found the target line
                if current_line_num == line_number:
                    execution_count = count_int
                    return {
                        'is_executed': execution_count > 0,
                        'execution_count': execution_count
                    }

        # If we reach here, the line was not found in the output
        # This could mean:
        # 1. The line is not executable (e.g., blank line, comment, declaration)
        # 2. The line number is out of range
        # Return a default "not executed" result
        return {
            'is_executed': False,
            'execution_count': 0
        }

    def get_function_regions(self, file_path: str, function_name: str) -> List[Dict[str, Any]]: # Based on JSON data
        """
        Get function region coverage details.
        Args:
            file_path: Source file path
            function_name: Function name
        Returns:
            List of region info, each containing:
            - start_line: Start line number
            - start_col: Start column number
            - end_line: End line number
            - end_col: End column number
            - execution_count: Execution count
            - is_covered: Whether region is covered
        """
        coverage_data = self._get_coverage_data()
        file_path = os.path.abspath(file_path)

        # Functions are stored in data[0]['functions'], not in files
        for function in coverage_data.get('data', [{}])[0].get('functions', []):
            if function['name'] == function_name:
                # Check if this function belongs to the specified file
                filenames = function.get('filenames', [])
                abs_filenames = [os.path.abspath(f) for f in filenames]
                if file_path not in abs_filenames:
                    continue

                # Get the file_id for the target file
                file_id = abs_filenames.index(file_path)

                # Traverse regions within the function.
                # Region format: [start_line, start_col, end_line, end_col, execution_count, file_id, expanded_file_id, kind]
                regions = []
                for region in function.get('regions', []):
                    if len(region) >= 6 and region[5] == file_id:
                        regions.append({
                            'start_line': region[0],
                            'start_col': region[1],
                            'end_line': region[2],
                            'end_col': region[3],
                            'execution_count': region[4],
                            'is_covered': region[4] > 0,
                            'file_id': region[5]
                        })
                return regions

        raise ValueError(f"Function '{function_name}' not found in file '{file_path}'")



    def generate_full_report(self, max_lines: int = 40) -> str:
        """
        Generate coverage summary report (a human-readable big table).
        Args:
            max_lines: Maximum number of lines to return (default: 40)
        Returns:
            Coverage report string, truncated if exceeds max_lines
        """
        cmd = [
            self.llvm_cov_path,
            'report',
            self.binary_path,
            f'-instr-profile={self.profdata_path}'
        ]
        # print(f"Running command: {' '.join(cmd)}")
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            raise RuntimeError(f"llvm-cov command failed: {result.stderr}")

        # Truncate output if exceeds max_lines
        lines = result.stdout.splitlines()
        if len(lines) > max_lines:
            truncated_lines = lines[:max_lines]
            omitted_count = len(lines) - max_lines
            truncated_lines.append(f"... ({omitted_count} lines omitted)")
            return '\n'.join(truncated_lines)
        # If not exceeding max_lines, return full output
        return result.stdout

    def generate_html_report(self, output_dir: str) -> str:
        """
        Generate HTML coverage report.
        Args:
            output_dir: Output directory path
        Returns:
            Path to main HTML report file
        """
        output_dir = os.path.abspath(output_dir)
        os.makedirs(output_dir, exist_ok=True)

        cmd = [
            self.llvm_cov_path,
            'show',
            self.binary_path,
            f'-instr-profile={self.profdata_path}',
            '-format=html',
            f'-output-dir={output_dir}'
        ]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            raise RuntimeError(f"llvm-cov command failed: {result.stderr}")

        # Return main HTML file path
        index_path = os.path.join(output_dir, 'index.html')
        if not os.path.isfile(index_path):
            raise RuntimeError("llvm-cov: HTML report generation failed.")
        return index_path

    def clear_data(self) -> None:
        """
        Clear cached coverage data to free memory.
        Example:
            cov = LLVMCovUtils(binary_path='/path/to/binary')
            cov.update_profile_data('/path/to/coverage.profraw')
            result = cov.get_function_coverage('file.c', 'main')
            # ... process result ...
            cov.clear_data()  # Free memory
        """
        if self._coverage_data is not None: # FIXED: Avoid operating on a None object!
            self._coverage_data.clear()
        self._coverage_data = None

def main():
    """
    Main function providing CLI for LLVMCovUtils.
    """
    import argparse
    import sys

    parser = argparse.ArgumentParser(
        description='LLVM Coverage Analysis Tool',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Usage examples:
  # Generate coverage summary report
  python llvm_cov.py --binary ./a.out --profraw coverage.profraw --report

  # Query function coverage
  python llvm_cov.py --binary ./a.out --profraw coverage.profraw --function-coverage main.c main

  # Query line coverage
  python llvm_cov.py --binary ./a.out --profraw coverage.profraw --line-coverage main.c 42

  # Generate HTML report
  python llvm_cov.py --binary ./a.out --profraw coverage.profraw --html-report ./coverage_html
        """
    )

    parser.add_argument('--binary', '-b', required=True,
                        help='Path to instrumented binary')
    parser.add_argument('--profraw', '-p', required=True,
                        help='Path to profraw file (will be converted to profdata automatically)')
    parser.add_argument('--llvm-cov', default='llvm-cov',
                        help='Path to llvm-cov tool (default: llvm-cov)')
    parser.add_argument('--llvm-profdata', default='llvm-profdata',
                        help='Path to llvm-profdata tool (default: llvm-profdata)')

    # Action options
    action_group = parser.add_mutually_exclusive_group(required=True)
    action_group.add_argument('--report', action='store_true',
                              help='Generate coverage summary report')
    action_group.add_argument('--function-coverage', nargs=2, metavar=('FILE', 'FUNCTION'),
                              help='Query function coverage details')
    action_group.add_argument('--function-regions', nargs=2, metavar=('FILE', 'FUNCTION'),
                              help='Query function region coverage')
    action_group.add_argument('--line-coverage', nargs=2, metavar=('FILE', 'LINE'),
                              help='Query line coverage')
    action_group.add_argument('--html-report', metavar='OUTPUT_DIR',
                              help='Generate HTML coverage report')

    args = parser.parse_args()

    try:
        # Initialize utility class
        cov_utils = LLVMCovUtils(
            binary_abs_path=args.binary,
            llvm_cov_path=args.llvm_cov,
            llvm_profdata_path=args.llvm_profdata
        )
        cov_utils.update_profile_data(args.profraw)

        # Execute corresponding action
        if args.report:
            print("=== Coverage Report ===")
            print(cov_utils.generate_full_report())

        elif args.function_coverage:
            file_path, function_name = args.function_coverage
            print(f"=== Function Coverage: {function_name} in {file_path} ===")
            result = cov_utils.get_function_coverage(file_path, function_name)
            print(f"Executed: {result['is_executed']}")
            print(f"Execution Count: {result['execution_count']}")
            print(f"Regions: {result['regions_covered']}/{result['regions_total']} covered")

        elif args.function_regions:
            file_path, function_name = args.function_regions
            print(f"=== Function Regions: {function_name} in {file_path} ===")
            regions = cov_utils.get_function_regions(file_path, function_name)
            for i, region in enumerate(regions, 1):
                status = "COVERED" if region['is_covered'] else "NOT COVERED"
                print(f"Region {i}: [{region['start_line']}:{region['start_col']} - "
                      f"{region['end_line']}:{region['end_col']}] "
                      f"Count: {region['execution_count']} ({status})")

        elif args.line_coverage:
            file_path, line_number = args.line_coverage
            line_number = int(line_number)
            print(f"=== Line Coverage: {file_path}:{line_number} ===")
            result = cov_utils.get_line_coverage(file_path, line_number)
            print(f"Executed: {result['is_executed']}")
            print(f"Execution Count: {result['execution_count']}")

        elif args.html_report:
            print(f"=== Generating HTML Report to {args.html_report} ===")
            index_path = cov_utils.generate_html_report(args.html_report)
            print(f"HTML report generated successfully!")
            print(f"Open {index_path} in your browser to view the report.")

    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == '__main__':
    main()
